import { expect, test } from '@playwright/test';
import { openSignedIn } from './sign-in';

/**
 * The assistant tells people they are talking to an AI (EU AI Act art. 50) before they write,
 * in the language the app picked, with a link to the privacy policy.
 */
const ASSISTANT_URL = process.env.E2E_ASSISTANT_URL ?? 'http://assistant.celine.localhost';
const WEBAPP_URL = process.env.E2E_WEBAPP_URL ?? 'http://webapp.celine.localhost';

const NOTICE: Record<string, { browser: string; text: RegExp }> = {
  en: { browser: 'en-GB', text: /Answers are generated by AI and can be wrong/ },
  it: { browser: 'it-IT', text: /Le risposte sono generate dall'IA e possono essere errate/ },
  es: { browser: 'es-ES', text: /Las respuestas las genera una IA y pueden contener errores/ },
};

for (const [lang, { browser, text }] of Object.entries(NOTICE)) {
  test.describe(`assistant in ${lang}`, () => {
    test.use({ locale: browser });

    test('shows the AI notice beside the composer, linking the privacy policy', async ({ page }) => {
      await openSignedIn(page, ASSISTANT_URL);

      const notice = page.locator('.ai-notice');
      await expect(notice).toBeVisible();
      await expect(notice).toContainText(text);

      const link = notice.getByRole('link');
      await expect(link).toHaveAttribute('href', /.+/);
      await expect(link).toHaveAttribute('target', '_blank');
      await expect(link).toHaveAttribute('rel', /noopener/);
    });
  });
}

/**
 * The embedded case: an "ask the assistant" button in the webapp opens `/assistant?prompt=…`,
 * and ChatCore sends that prompt on its own as the page loads. The member never types, so the
 * notice has to be on that page as the answer arrives, in the webapp's own language files.
 */
for (const [lang, { browser, text }] of Object.entries(NOTICE)) {
  test.describe(`assistant embedded in the webapp, in ${lang}`, () => {
    test.use({ locale: browser });

    test('shows the AI notice when a prompt arrives from an ask-the-assistant button', async ({ page }) => {
      await openSignedIn(page, `${WEBAPP_URL}/assistant?prompt=${encodeURIComponent('hello')}`);

      const landed = new URL(page.url()).pathname;
      if (landed !== '/assistant') {
        didNotRun('the webapp sent this account somewhere else before the page', [
          `Signing in as E2E_USER landed on ${landed}, not /assistant.`,
          'A first-run gate (terms acceptance) stands in front of every page for an account',
          'that has never been through it; accepting on somebody\'s behalf is not this check\'s to do.',
        ]);
      }

      const notice = page.locator('.ai-notice');
      await expect(notice).toBeVisible();
      await expect(notice).toContainText(text);

      const link = notice.getByRole('link');
      await expect(link).toHaveAttribute('href', /.+/);
      await expect(link).toHaveAttribute('target', '_blank');
      await expect(link).toHaveAttribute('rel', /noopener/);
    });
  });
}

function didNotRun(what: string, detail: string[]): never {
  const reason = [
    '',
    `  AI NOTICE CHECK DID NOT RUN — ${what}`,
    ...detail.map((line) => `  ${line}`),
    '  This is a skip, not a pass. Nothing about the notice was checked.',
    '',
  ].join('\n');
  console.log(reason);
  test.skip(true, reason);
  throw new Error(reason); // unreachable; satisfies `never`
}
